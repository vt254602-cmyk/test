const seed: Question[] = [...seedTest1, ...seedTest2];

type QuizState = {
  questions: Question[];
  addQuestion: (q: Omit<Question, "id">) => void;
  updateQuestion: (id: string, q: Omit<Question, "id">) => void;
  deleteQuestion: (id: string) => void;
};

export const useQuizStore = create<QuizState>((set) => ({
  questions: seed,
  addQuestion: (q) =>
    set((state) => ({
      questions: [...state.questions, { ...q, id: crypto.randomUUID() } as Question],
    })),
  updateQuestion: (id, q) =>
    set((state) => ({
      questions: state.questions.map((existing) =>
        existing.id === id ? ({ ...q, id } as Question) : existing,
      ),
    })),
  deleteQuestion: (id) =>
    set((state) => ({
      questions: state.questions.filter((q) => q.id !== id),
    })),
}));
