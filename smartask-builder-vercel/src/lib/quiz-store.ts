const mcq = (
  testId: TestId,
  id: string,
  question: string,
  options: string[],
  correct: number | number[],
  explanation = "",
): McqQuestion => ({
  id,
  testId,
  type: "mcq",
  question,
  options,
  answer: Array.isArray(correct) ? correct.map((i) => options[i]) : options[correct],
  explanation,
});

